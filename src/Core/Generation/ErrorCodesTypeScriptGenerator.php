<?php

declare(strict_types=1);

namespace Edf\Core\Generation;

use Edf\Core\ResolvedErrorDefinition;

/**
 * Membentuk isi `error-codes.ts`: object `as const` dan union type dari error code.
 * Hanya error code yang dibawa; metadata tersedia pada JSON catalog.
 *
 * @see docs/decisions/1-error-definition-framework/1.10-generator-error-codes-typescript.md
 */
final class ErrorCodesTypeScriptGenerator
{
    /**
     * @param iterable<ResolvedErrorDefinition> $definitions
     */
    public function generate(iterable $definitions): string
    {
        $codes = [];

        foreach ($definitions as $definition) {
            $codes[] = $definition->code;
        }

        sort($codes, SORT_STRING);

        $lines = [
            '// This file is generated by Error Definition Framework.',
            '// Do not edit manually.',
            '',
            'export const ERROR_CODES = {',
        ];

        foreach (array_unique($codes) as $code) {
            // Format code hanya berisi A-Z, 0-9, dan '-' sehingga tidak perlu escaping.
            $lines[] = sprintf("  '%s': '%s',", str_replace('-', '_', $code), $code);
        }

        array_push(
            $lines,
            '} as const;',
            '',
            'export type ErrorCode =',
            '  (typeof ERROR_CODES)[keyof typeof ERROR_CODES];',
        );

        return implode("\n", $lines)."\n";
    }
}
