<?php

declare(strict_types=1);

namespace Edf\Tests\Unit;

use Edf\Core\ErrorCategory;
use Edf\Core\ErrorSeverity;
use Edf\Core\Generation\ErrorCodesTypeScriptGenerator;
use Edf\Core\ResolvedErrorDefinition;
use PHPUnit\Framework\TestCase;

final class ErrorCodesTypeScriptGeneratorTest extends TestCase
{
    public function test_generates_sorted_const_object_and_union_type(): void
    {
        $content = (new ErrorCodesTypeScriptGenerator())->generate([
            $this->definition('USR-BR-001'),
            $this->definition('SM-WF-001'),
            $this->definition('3DS-INT-001'),
            $this->definition('SM-VAL-001'),
        ]);

        $this->assertSame(<<<'TS'
            // This file is generated by Error Definition Framework.
            // Do not edit manually.

            export const ERROR_CODES = {
              '3DS_INT_001': '3DS-INT-001',
              'SM_VAL_001': 'SM-VAL-001',
              'SM_WF_001': 'SM-WF-001',
              'USR_BR_001': 'USR-BR-001',
            } as const;

            export type ErrorCode =
              (typeof ERROR_CODES)[keyof typeof ERROR_CODES];

            TS, $content);
    }

    public function test_output_is_deterministic_and_lf_only(): void
    {
        $generator = new ErrorCodesTypeScriptGenerator();
        $first = $generator->generate([$this->definition('B-WF-001'), $this->definition('A-WF-001')]);
        $second = $generator->generate([$this->definition('A-WF-001'), $this->definition('B-WF-001')]);

        $this->assertSame($first, $second);
        $this->assertStringNotContainsString("\r", $first);
        $this->assertStringEndsWith(";\n", $first);
    }

    private function definition(string $code): ResolvedErrorDefinition
    {
        return new ResolvedErrorDefinition(
            code: $code,
            message: 'Pesan.',
            category: ErrorCategory::WORKFLOW,
            httpStatus: 409,
            severity: ErrorSeverity::MEDIUM,
            retryable: false,
        );
    }
}
